"""한국 식단 인스턴스 분할 데이터셋 파이프라인 (YOLOv8-Seg 규격)."""
import argparse
import json
import os
from pathlib import Path
import cv2
import numpy as np

# 식약처(KFDA) 연계 10종 식단 및 의약품 클래스 정의
CLASSES = {
    0: "white_rice",
    1: "spinach_namul",
    2: "kimchi_stew",
    3: "soybean_paste_stew",
    4: "bulgogi",
    5: "grilled_salmon",
    6: "banana",
    7: "apple",
    8: "boiled_egg",
    9: "coumadin_pill",
}


def create_directory_structure(base_dir: Path) -> tuple[Path, Path, Path, Path]:
    """YOLOv8-Seg 표준 디렉터리 트리를 생성합니다."""
    img_train = base_dir / "images" / "train"
    img_val = base_dir / "images" / "val"
    lbl_train = base_dir / "labels" / "train"
    lbl_val = base_dir / "labels" / "val"

    for p in [img_train, img_val, lbl_train, lbl_val]:
        p.mkdir(parents=True, exist_ok=True)

    return img_train, img_val, lbl_train, lbl_val


def write_dataset_yaml(base_dir: Path, yaml_path: Path):
    """YOLOv8 학습용 kfood.yaml 메타데이터 파일을 기록합니다."""
    yaml_content = f"""# Auto-generated by dataset_pipeline.py
path: {base_dir.resolve()}
train: images/train
val: images/val

names:
"""
    for idx, name in CLASSES.items():
        yaml_content += f"  {idx}: {name}\n"

    with open(yaml_path, "w", encoding="utf-8") as f:
        f.write(yaml_content)
    print(f">> [Manifest] 메타데이터 기록 완료: {yaml_path}")


def convert_coco_json_to_yolo(coco_json_path: str, images_src_dir: str, base_dir: Path):
    """COCO 형식(AI Hub 표준)의 JSON 어노테이션을 YOLOv8-Seg 폴리곤 텍스트로 변환합니다."""
    with open(coco_json_path, "r", encoding="utf-8") as f:
        coco_data = json.load(f)

    img_train, _, lbl_train, _ = create_directory_structure(base_dir)

    names_to_id = {name: index for index, name in CLASSES.items()}
    category_map = {}
    for category in coco_data.get("categories", []):
        name = category["name"]
        if name not in names_to_id:
            raise ValueError(f"지원하지 않는 COCO 클래스: {name}")
        category_map[category["id"]] = names_to_id[name]
    if not category_map:
        raise ValueError("COCO categories의 명시적 클래스 매핑이 필요합니다.")

    images_map = {img["id"]: img for img in coco_data["images"]}
    annotations_by_img = {}
    for ann in coco_data["annotations"]:
        annotations_by_img.setdefault(ann["image_id"], []).append(ann)

    converted_count = 0
    for img_id, img_info in images_map.items():
        file_name = img_info["file_name"]
        src_img_path = Path(images_src_dir) / file_name
        if not src_img_path.exists():
            continue

        width = img_info["width"]
        height = img_info["height"]

        # 이미지 복사/심볼릭 링크
        dst_img_path = img_train / file_name
        if not dst_img_path.exists():
            os.symlink(src_img_path.resolve(), dst_img_path)

        # 라벨 파일 작성 (Polygon 좌표 정규화)
        txt_name = Path(file_name).stem + ".txt"
        lbl_path = lbl_train / txt_name

        with open(lbl_path, "w", encoding="utf-8") as lf:
            anns = annotations_by_img.get(img_id, [])
            for a in anns:
                cat_id = a["category_id"]
                # 0-indexed 보정 또는 클래스 매핑
                if cat_id not in category_map:
                    raise ValueError(f"정의되지 않은 category_id: {cat_id}")
                cls_idx = category_map[cat_id]
                segmentation = a.get("segmentation", [])
                if not segmentation:
                    continue

                for poly in segmentation:
                    if len(poly) < 6:
                        continue
                    normalized_poly = []
                    for i in range(0, len(poly), 2):
                        nx = np.clip(poly[i] / width, 0.0, 1.0)
                        ny = np.clip(poly[i + 1] / height, 0.0, 1.0)
                        normalized_poly.extend([f"{nx:.6f}", f"{ny:.6f}"])
                    lf.write(f"{cls_idx} {' '.join(normalized_poly)}\n")

        converted_count += 1

    print(f">> [Converter] COCO 어노테이션 {converted_count}건 변환 완료.")


def generate_bootstrap_data(base_dir: Path, num_train: int = 80, num_val: int = 20):
    """RTX 5090 학습 및 수렴 검증용 정밀 10종 다각형(Polygon) 데이터셋을 생성합니다."""
    img_train, img_val, lbl_train, lbl_val = create_directory_structure(base_dir)

    splits = [
        (img_train, lbl_train, num_train),
        (img_val, lbl_val, num_val),
    ]

    # 클래스별 렌더링 색상 (BGR)
    palette = {
        0: (230, 230, 230),  # 쌀밥 (하양)
        1: (40, 140, 40),    # 시금치나물 (초록)
        2: (20, 40, 200),    # 김치찌개 (빨강)
        3: (40, 90, 160),    # 된장찌개 (갈색)
        4: (30, 60, 100),    # 불고기 (진갈색)
        5: (80, 110, 220),   # 연어구이 (주황)
        6: (60, 210, 240),   # 바나나 (노랑)
        7: (100, 100, 240),  # 사과 (빨강)
        8: (200, 220, 240),  # 삶은계란 (연노랑)
        9: (220, 220, 220),  # 쿠마딘정 (타원형 알약)
    }

    total_generated = 0
    for img_dir, lbl_dir, count in splits:
        for idx in range(count):
            img_name = f"kfood_{idx:05d}.jpg"
            lbl_name = f"kfood_{idx:05d}.txt"

            img_path = img_dir / img_name
            lbl_path = lbl_dir / lbl_name

            # 1. 640x640 배경 (식탁 텍스처 노이즈 모사)
            img = np.full((640, 640, 3), 190, dtype=np.uint8)
            noise = np.random.randint(-15, 15, (640, 640, 3), dtype=np.int16)
            img = np.clip(img.astype(np.int16) + noise, 0, 255).astype(np.uint8)

            # 2. 식기(접시/그릇) 렌더링
            cv2.ellipse(img, (320, 320), (220, 220), 0, 0, 360, (240, 240, 240), -1)
            cv2.ellipse(img, (320, 320), (220, 220), 0, 0, 360, (170, 170, 170), 3)

            # 3. 1~2개 음식 인스턴스 배치
            num_items = np.random.randint(1, 3)
            lines = []

            for _ in range(num_items):
                cls_id = np.random.randint(0, len(CLASSES))
                center_x = np.random.randint(220, 420)
                center_y = np.random.randint(220, 420)
                radius = np.random.randint(45, 95)

                # 다각형(Polygon) 정점 생성 (8~12개 정점)
                num_pts = np.random.randint(8, 13)
                angles = np.sort(np.random.rand(num_pts) * 2 * np.pi)
                poly_pts = []
                norm_poly = []

                for angle in angles:
                    r = radius * np.random.uniform(0.75, 1.25)
                    px = int(np.clip(center_x + r * np.cos(angle), 10, 630))
                    py = int(np.clip(center_y + r * np.sin(angle), 10, 630))
                    poly_pts.append([px, py])
                    norm_poly.extend([f"{px / 640.0:.6f}", f"{py / 640.0:.6f}"])

                pts_arr = np.array(poly_pts, dtype=np.int32).reshape((-1, 1, 2))
                cv2.fillPoly(img, [pts_arr], palette[cls_id])
                lines.append(f"{cls_id} {' '.join(norm_poly)}\n")

            cv2.imwrite(str(img_path), img)
            with open(lbl_path, "w", encoding="utf-8") as lf:
                lf.writelines(lines)

            total_generated += 1

    print(f">> [Bootstrap] 훈련/검증용 정밀 폴리곤 데이터 {total_generated}장 적재 완료.")


def main():
    parser = argparse.ArgumentParser(description="VoluMeal-Align 데이터셋 적재 엔진")
    parser.add_argument("--mode", choices=["bootstrap", "convert"], default="bootstrap",
                        help="실행 모드: bootstrap(즉시 생성) 또는 convert(외부 COCO JSON 변환)")
    parser.add_argument("--base-dir", default="/workspace/backend/data/kfood",
                        help="데이터셋 루트 디렉터리 경로")
    parser.add_argument("--coco-json", default=None, help="변환할 COCO 형식 JSON 파일 경로")
    parser.add_argument("--images-src", default=None, help="원천 원본 이미지 폴더 경로")
    parser.add_argument("--num-train", type=int, default=120, help="부트스트랩 Train 이미지 수")
    parser.add_argument("--num-val", type=int, default=30, help="부트스트랩 Val 이미지 수")

    args = parser.parse_args()
    base_dir = Path(args.base_dir)
    yaml_path = base_dir.parent / "kfood.yaml"

    if args.mode == "bootstrap":
        print(">> [Mode] 부트스트랩 모드: RTX 5090 학습 파이프라인 검증용 데이터셋 생성 시작")
        generate_bootstrap_data(base_dir, num_train=args.num_train, num_val=args.num_val)
        write_dataset_yaml(base_dir, yaml_path)
    elif args.mode == "convert":
        if not args.coco_json or not args.images_src:
            raise ValueError("--coco-json 및 --images-src 경로가 필수 지정되어야 합니다.")
        print(">> [Mode] 변환 모드: 외부 COCO 어노테이션 포맷 변환 시작")
        convert_coco_json_to_yolo(args.coco_json, args.images_src, base_dir)
        write_dataset_yaml(base_dir, yaml_path)


if __name__ == "__main__":
    main()
